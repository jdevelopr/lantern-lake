// The northern boots are two rows taller: take the storybook legs and thicken the boots,
// with a light fur band at the top of the near boot.
function tallBoots(rows) {
  const t = rows.slice(0, 5), b = rows.slice(5);
  const fur = b[0].replace(/B/g, 'b').replace(/D/g, 'D');
  return [...t, fur, b[0], b[1], b[2], b[2]];
}

