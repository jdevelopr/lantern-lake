// Style C, "snowbound north": 32 px, bundled up in fur-collared parkas, mittens and
// fur-topped boots, round faces with rosy cheeks. Shares the storybook head geometry
// (hair and hats), with its own face, torsos and chunkier legs.
import { pm } from './px.js';
